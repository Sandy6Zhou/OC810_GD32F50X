#include "rtt_logger.h"
#include "SEGGER_RTT.h"

/*********************************************************************
 * @brief   初始化RTT日志
 * @param   none
 * @return  none
 * @note    调用 Segger RTT 库初始化函数
 *********************************************************************/
void rtt_logger_init(void)
{
    SEGGER_RTT_Init();
}

/*********************************************************************
 * @brief   通过RTT写入数据
 * @param   data 数据指针
 * @param   len 数据长度
 * @return  实际写入的字节数
 * @note    使用 RTT Channel 0
 *********************************************************************/
int rtt_logger_write(const char *data, int len)
{
    return SEGGER_RTT_Write(0, data, len);
}
