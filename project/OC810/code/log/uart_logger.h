#ifndef __UART_LOGGER_H__
#define __UART_LOGGER_H__

#include <stdint.h>

/*********************************************************************
 * @brief   初始化串口日志
 * @param   none
 * @return  none
 * @note    使用USART0，PA9引脚，波特率115200
 *********************************************************************/
void uart_logger_init(void);

/*********************************************************************
 * @brief   通过串口写入数据
 * @param   data 数据指针
 * @param   len 数据长度
 * @return  实际写入的字节数
 * @note    轮询方式发送，阻塞等待发送完成
 *********************************************************************/
int uart_logger_write(const char *data, int len);

#endif /* __UART_LOGGER_H__ */
