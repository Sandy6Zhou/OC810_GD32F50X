#ifndef __PARAM_MANAGER_H__
#define __PARAM_MANAGER_H__

#include <stdint.h>
#include <stdbool.h>

/*******************************************************************************
 * 错误码定义
 ******************************************************************************/

#define PARAM_OK                  0             /**< 成功 */
#define PARAM_ERR_INIT            -1            /**< 未初始化 */
#define PARAM_ERR_NOT_FOUND       -2            /**< 参数不存在 */
#define PARAM_ERR_CRC             -3            /**< CRC校验失败 */
#define PARAM_ERR_MAGIC           -4            /**< 魔数错误 */
#define PARAM_ERR_SIZE            -5            /**< 大小错误 */
#define PARAM_ERR_FORMAT          -6            /**< 格式错误 */
#define PARAM_ERR_FILE            -7            /**< 文件操作错误 */
#define PARAM_ERR_MEMORY          -8            /**< 内存错误 */

/*******************************************************************************
 * 公开API
 ******************************************************************************/

/*******************************************************************************
 * @brief   初始化参数管理系统
 * @return  PARAM_OK: 成功，其他: 错误码
 * @note    初始化LittleFS，创建参数目录
 *******************************************************************************/
int param_manager_init(void);

/*******************************************************************************
 * @brief   反初始化参数管理系统
 * @return  PARAM_OK: 成功，其他: 错误码
 *******************************************************************************/
int param_manager_deinit(void);

/*******************************************************************************
 * @brief   读取参数
 * @param   param_id    参数ID
 * @param   buf         输出缓冲区
 * @param   len         缓冲区长度
 * @return  实际读取字节数，<0: 错误码
 *******************************************************************************/
int param_read(uint16_t param_id, void *buf, uint16_t len);

/*******************************************************************************
 * @brief   写入参数
 * @param   param_id    参数ID
 * @param   buf         数据缓冲区
 * @param   len         数据长度
 * @return  PARAM_OK: 成功，<0: 错误码
 *******************************************************************************/
int param_write(uint16_t param_id, const void *buf, uint16_t len);

/*******************************************************************************
 * @brief   删除参数
 * @param   param_id    参数ID
 * @return  PARAM_OK: 成功，<0: 错误码
 *******************************************************************************/
int param_delete(uint16_t param_id);

/*******************************************************************************
 * @brief   检查参数是否存在
 * @param   param_id    参数ID
 * @return  1: 存在，0: 不存在，<0: 错误
 *******************************************************************************/
int param_exists(uint16_t param_id);

/*******************************************************************************
 * @brief   获取参数大小
 * @param   param_id    参数ID
 * @return  参数字节数，<0: 错误码
 *******************************************************************************/
int param_get_size(uint16_t param_id);

/*******************************************************************************
 * @brief   清空所有参数
 * @return  PARAM_OK: 成功，<0: 错误码
 * @note    删除params目录下所有文件
 *******************************************************************************/
int param_clear_all(void);

/*******************************************************************************
 * @brief   验证参数数据完整性
 * @return  PARAM_OK: 完整，<0: 损坏
 *******************************************************************************/
int param_verify_integrity(void);

#endif /* __PARAM_MANAGER_H__ */
