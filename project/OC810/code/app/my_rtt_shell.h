#ifndef __MY_RTT_SHELL_H__
#define __MY_RTT_SHELL_H__

#include <stdint.h>
#include <stdbool.h>
#include "FreeRTOS.h"
#include "my_config.h"

/* Shell配置从 my_config.h 获取 */
#define SHELL_LINE_MAX          (MY_SHELL_LINE_MAX)
#define SHELL_ARGC_MAX          (MY_SHELL_ARGC_MAX)
#define SHELL_PROMPT            (MY_SHELL_PROMPT)

/*===========================================================================
 * 命令处理函数类型
 *===========================================================================*/

/**
 * @brief Shell命令处理函数原型
 * @param argc  参数个数（含命令名本身）
 * @param argv  参数数组（argv[0] = 命令名）
 * @return 0=成功，<0=错误码
 */
typedef int (*shell_cmd_handler_t)(int argc, char *argv[]);

/*===========================================================================
 * 命令注册结构体
 *===========================================================================*/

typedef struct
{
    const char          *name;      /* 命令名称（如 "help", "sys"） */
    const char          *help;      /* 简要帮助说明 */
    shell_cmd_handler_t handler;    /* 处理函数 */
} shell_cmd_t;

/*===========================================================================
 * 公开API
 *===========================================================================*/

/*********************************************************************
 * @brief   初始化并启动RTT Shell任务
 * @return  0: 成功，<0: 失败
 * @note    创建FreeRTOS任务，开始轮询RTT输入
 *********************************************************************/
int my_rtt_shell_init(void);

/*********************************************************************
 * @brief   注册自定义命令到Shell
 * @param   cmd     命令结构体指针（需为静态/全局变量，Shell仅保存指针）
 * @return  0: 成功，<0: 失败（命令表已满或参数无效）
 * @note    线程安全，可在任意时刻调用
 *********************************************************************/
int my_rtt_shell_register_cmd(const shell_cmd_t *cmd);

/*********************************************************************
 * @brief   Shell输出字符串（供命令处理函数使用）
 * @param   str     字符串指针
 *********************************************************************/
void shell_print(const char *str);

/*********************************************************************
 * @brief   Shell格式化输出（供命令处理函数使用）
 * @param   fmt     格式化字符串
 * @param   ...     可变参数
 *********************************************************************/
void shell_printf(const char *fmt, ...);

#endif /* __MY_RTT_SHELL_H__ */
