#ifndef __MY_BL_UTILS_H__
#define __MY_BL_UTILS_H__

#include <stdint.h>

/*********************************************************************
 * @brief   MD5 上下文结构（用于流式计算）
 *********************************************************************/
typedef struct
{
    uint32_t state[4];      /* MD5 状态寄存器 */
    uint32_t count[2];      /* 比特计数（低32位，高32位） */
    uint8_t  buffer[64];    /* 数据缓冲区 */
} my_bl_md5_ctx_t;

/*********************************************************************
 * @brief   CRC16-CCITT 计算（查表法）
 * @param   data  数据缓冲区指针
 * @param   len   数据长度（字节）
 * @return  CRC16 校验值
 * @note    固定 CCITT 多项式 0x1021，初始值 0xFFFF，输出取反
 *          查表法：使用 256 项预计算表，计算速度快
 *********************************************************************/
uint16_t my_bl_crc16_table(const uint8_t *data, uint32_t len);

/*********************************************************************
 * @brief   MD5 初始化
 * @param   ctx  MD5 上下文指针
 * @return  None
 *********************************************************************/
void my_bl_md5_init(my_bl_md5_ctx_t *ctx);

/*********************************************************************
 * @brief   MD5 更新（可多次调用）
 * @param   ctx   MD5 上下文指针
 * @param   data  数据缓冲区指针
 * @param   len   数据长度（字节）
 * @return  None
 *********************************************************************/
void my_bl_md5_update(my_bl_md5_ctx_t *ctx, const uint8_t *data, uint32_t len);

/*********************************************************************
 * @brief   MD5 最终计算
 * @param   ctx     MD5 上下文指针
 * @param   output  输出缓冲区（必须至少 16 字节）
 * @return  None
 * @note    调用此函数后，ctx 不再有效
 *********************************************************************/
void my_bl_md5_final(my_bl_md5_ctx_t *ctx, uint8_t *output);

/*********************************************************************
 * @brief   执行系统复位
 * @param   None
 * @return  None
 * @note    调用 NVIC_SystemReset()，该函数不会返回；末尾 while(1) 为防御性代码
 *********************************************************************/
void my_bl_system_reset(void);

#endif /* __MY_BL_UTILS_H__ */
